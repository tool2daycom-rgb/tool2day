function pack(
  overrides: Partial<Omit<UiMessages, "categories">> & {
    categories?: Partial<UiMessages["categories"]>;
  },
): UiMessages {
  return {
    ...en,
    ...overrides,
    categories: {
      ...en.categories,
      ...(overrides.categories || {}),
    },
  };
}

